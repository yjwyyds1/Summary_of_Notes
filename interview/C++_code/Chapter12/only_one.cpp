#include <algorithm>   // for std::swap
#include <iostream>

// ============================================================
//  第 1 节: 变量是什么, & 在语句里 = 查门牌号
// ============================================================
void section1()
{
    std::cout << "\n===== 第1节: 变量与地址 =====\n";

    int x { 5 };      // 开一间房: 名字叫 x, 客人是 5
    int y { 9 };      // 又开一间房: 名字叫 y, 客人是 9

    std::cout << "x 的值:      " << x   << '\n';
    std::cout << "y 的值:      " << y   << '\n';
    std::cout << "x 的地址(&x): " << &x  << '\n';   // & 在语句里 = 查门牌号
    std::cout << "y 的地址(&y): " << &y  << '\n';   // 每间房的门牌号都不同

    // 调试观察点: 用"监视"窗口看 &x 和 &y, 你会发现两个地址不一样
}

// ============================================================
//  第 2 节: 指针 = 一张写着门牌号的纸条
//           声明里的 * = "这是个指针"
//           语句里的 * = "按号找房" (解引用)
// ============================================================
void section2()
{
    std::cout << "\n===== 第2节: 指针基础 =====\n";

    int x { 5 };
    int* p { &x };    // 造一张纸条 p, 上面写着 x 的门牌号

    std::cout << "x 的值:         " << x     << '\n';
    std::cout << "x 的地址:       " << &x    << '\n';
    std::cout << "p 存的地址:     " << p     << '\n';   // 应该和 &x 一样!
    std::cout << "*p (按号找房):  " << *p    << '\n';   // 找到 x 的房, 看客人

    *p = 10;    // 按号找到 x 的房, 把客人换成 10

    std::cout << "执行 *p = 10 之后, x = " << x << '\n';  // x 变成了 10!
    std::cout << "x 的地址始终没变:      " << &x << '\n';

    // 调试观察点: 单步执行完 *p = 10 那行, 盯着变量窗口看 x 的变化
    // 结论: 通过纸条(*p)干的事, 就是对 x 本人干的事
}

// ============================================================
//  第 3 节: 纸条可以重写 (指针可以重新指向)
// ============================================================
void section3()
{
    std::cout << "\n===== 第3节: 指针重新指向 =====\n";

    int x { 5 };
    int y { 9 };
    int* p { &x };     // 纸条上写的是 x 的门牌号

    *p = 10;           // 这次改的是 x
    std::cout << "第一次 *p=10 后:  x=" << x << "  y=" << y << '\n';

    p = &y;            // 把纸条擦了, 重写成 y 的门牌号!
    std::cout << "p 重写后存的地址:  " << p   << '\n';
    std::cout << "y 的地址(对比):    " << &y  << '\n';

    *p = 20;           // 这次按的是 y 的门牌号, 改的是 y!
    std::cout << "第二次 *p=20 后:  x=" << x << "  y=" << y << '\n';

    // 调试观察点: 执行 p = &y 那行时, 盯着 p 的值从 &x 变成 &y
    // 结论: 指针(纸条)可以换目标, 这就是它和引用的最大区别
}

// ============================================================
//  第 4 节: nullptr = 纸条上写"我谁也不指"
//           铁律: 指针要么指向有效对象, 要么是 nullptr, 绝不留白
// ============================================================
    void section4()
{
    std::cout << "\n===== 第4节: 空指针 =====\n";

    int x { 5 };
    int* p { nullptr };   // 纸条上写着"无"

    std::cout << "p = " << p << '\n';          // 输出 0 (nullptr 的内部表示)

    if (p)                                   // 用之前先判空!
        std::cout << "*p = " << *p << '\n';  // 有号才敢找房
    else
        std::cout << "p 是空指针, 不指向任何房间, 不能 *p\n";

    p = &x;             // 现在纸条上有号了
    if (p)
        std::cout << "现在 p 有效, *p = " << *p << '\n';

    // 危险写法(注释掉了, 因为真执行会出事):
    // int* wild;   wild = ...;   野指针: 纸条从没写过, 内容是垃圾
    // *wild = 5;   按垃圾地址找房 = 未定义行为, 可能崩溃
}

// ============================================================
//  第 5 节: 引用 = 给房间起外号 (根本不是新房间!)
//           声明里的 & = "这是个外号"
// ============================================================
void section5()
{
    std::cout << "\n===== 第5节: 引用是别名 =====\n";

    int x { 5 };
    int& ref { x };    // 给 x 起外号叫 ref (注意: 这是声明, 所以 & 是外号标志)

    std::cout << "x 的值:       " << x     << '\n';
    std::cout << "ref 的值:     " << ref   << '\n';    // 外号看到的就是 x
    std::cout << "x 的地址:     " << &x    << '\n';
    std::cout << "ref 的地址:   " << &ref  << '\n';    // 和 &x 一模一样!

    ref = 10;    // 通过外号换客人 = x = 10
    std::cout << "ref = 10 之后: x=" << x << "  ref=" << ref << '\n';

    // 调试观察点: 监视窗口里 &ref 和 &x 是同一个地址!
    // 结论: ref 不是新变量, 它就是 x 的另一个名字
}

// ============================================================
//  第 6 节: 引用一生不能改指别人 (测验 Q2 原题!)
//           关键: 看这一行是不是在"声明新变量"
// ============================================================
void section6()
{
    std::cout << "\n===== 第6节: 引用不可重置 (Q2) =====\n";

    int x { 4 };
    int y { 6 };

    int& ref { x };    // ★声明 = 绑定, 一生锁定 x
    std::cout << "初始:      x=" << x << "  y=" << y << '\n';

    ++ref;             // 外号操作 = x 操作
    std::cout << "++ref:     x=" << x << "  y=" << y << '\n';   // x=5

    ref = y;           // ★陷阱! 这不是重新绑定, 这是赋值 = x = y
    std::cout << "ref = y:   x=" << x << "  y=" << y << '\n';   // x=6, y=6

    ++ref;             // 还是对 x 操作
    std::cout << "++ref:     x=" << x << "  y=" << y << '\n';   // x=7

    std::cout << "最终输出:  " << x << ' ' << y << '\n';         // 应该是 7 6

    // 调试观察点: 执行 ref = y 时, 盯着 x 从 5 变成 6, y 纹丝不动
    // 结论: ref 从头到尾都是 x 的外号. ref = y 意思是"把 y 的值塞进 x"
    // 对比: int& ref2 { y }; 才是给 y 起新外号(必须是声明新变量)
}

// ============================================================
//  第 7 节: const 锁谁? 从右往左读, 锁它左边的东西
// ============================================================
void section7()
{
    std::cout << "\n===== 第7节: const 指针 =====\n";

    int x { 5 };
    int y { 9 };

    // ---- 形态1: const int* p  锁"值"(纸条自由) ----
    const int* p1 { &x };
    std::cout << "[形态1] const int* p1: 锁值, 纸条自由\n";
    // *p1 = 10;   // 试试取消注释 → 编译错误! 不许通过 p1 改值
    p1 = &y;        // 纸条可以重写
    std::cout << "  p1 可以重指向 y: " << (p1 == &y ? "是" : "否") << '\n';
    std::cout << "  但 x 本人仍可直接改: ";
    x = 10;
    std::cout << "x=" << x << '\n';

    // ---- 形态2: int* const p  锁"纸条"(值自由) ----
    int* const p2 { &x };
    std::cout << "[形态2] int* const p2: 锁纸条, 值自由\n";
    // p2 = &y;    // 试试取消注释 → 编译错误! 纸条写死了
    *p2 = 20;       // 值可以改
    std::cout << "  *p2=20 之后 x=" << x << " (值可以改)\n";

    // ---- 形态3: const int* const p  双锁 ----
    const int* const p3 { &x };
    std::cout << "[形态3] const int* const p3: 双锁\n";
    // *p3 = 1;    // 取消注释 → 编译错误
    // p3 = &y;    // 取消注释 → 编译错误
    std::cout << "  什么都不能改, 只能读: *p3=" << *p3 << '\n';
}

// ============================================================
//  第 8 节: 传参三姿势 (对照记忆)
// ============================================================
void byValue(int x)       { x = 100; }             // 复印件, 改了白改
void byReference(int& x)  { x = 100; }             // 外号, 改的就是本体
void byAddress(int* p)    { if (p) *p = 100; }     // 纸条, 判空后按号改

void section8()
{
    std::cout << "\n===== 第8节: 传参三姿势 =====\n";

    int a { 1 }, b { 1 }, c { 1 };

    std::cout << "调用前:        a=" << a << "  b=" << b << "  c=" << c << '\n';

    byValue(a);        // 给复印件
    byReference(b);    // 给外号
    byAddress(&c);     // 给门牌号
    byAddress(nullptr);// 告诉它"没有房间", 它安全跳过

    std::cout << "byValue(a):    a=" << a << "  (没变! 改的是复印件)\n";
    std::cout << "byReference(b):b=" << b << "  (变了! 外号连着本体)\n";
    std::cout << "byAddress(&c): c=" << c << "  (变了! 按号找到房)\n";
    std::cout << "byAddress(nullptr): 安全跳过, 没崩\n";

    // 调试观察点: 进入 byValue 时看参数 x 的地址, 和 a 的地址不同(是副本)
    //             进入 byReference 时看参数 x 的地址, 和 b 一样(是别名)
}

// ============================================================
//  第 9 节: 按引用返回 (测验相关: 返回值的"值范畴")
// ============================================================
int& getMax(int& a, int& b)      // 返回的是外号, 不是复印件
{
    return (a > b) ? a : b;      // 把较大的那个的外号还回去
}

void section9()
{
    std::cout << "\n===== 第9节: 按引用返回 =====\n";

    int x { 5 };
    int y { 6 };

    std::cout << "初始: x=" << x << "  y=" << y << '\n';

    getMax(x, y) = 10;    // 返回的是 y 的外号(左值), 所以能直接赋值!
    std::cout << "getMax(x,y)=10 之后: x=" << x << "  y=" << y << '\n';  // y=10

    int v { getMax(x, y) };   // 接收方是普通变量 → 拿到的是复印件
    v = 999;
    std::cout << "v 是复印件, v=999 后: x=" << x << "  y=" << y << " (都不变)\n";

    int& r { getMax(x, y) };  // 接收方是引用 → 拿到外号
    r = 555;
    std::cout << "r 是外号,   r=555 后: x=" << x << "  y=" << y << " (y 变了)\n";

    // 绝对不能这么写(注释掉了):
    // int& bad() { int local {5}; return local; }  ← 函数结束 local 就销毁
    //                                               返回的外号悬垂 = 未定义行为!
}

// ============================================================
//  第 10 节: 测验 Q5 原题 sort2
// ============================================================
void sort2(int& lesser, int& greater)     // 两个外号, 直接连调用者的变量
{
    if (lesser > greater)                 // 顺序反了才动手
        std::swap(lesser, greater);       // 换客人 → 调用者的变量真的变了
}

void section10()
{
    std::cout << "\n===== 第10节: sort2 (Q5) =====\n";

    int x { 7 };
    int y { 5 };

    std::cout << "初始:              " << x << ' ' << y << '\n';   // 7 5

    sort2(x, y);    // 7>5, 交换
    std::cout << "第一次 sort2 后:   " << x << ' ' << y << '\n';   // 5 7

    sort2(x, y);    // 5<7, 不动(验证不乱改)
    std::cout << "第二次 sort2 后:   " << x << ' ' << y << '\n';   // 5 7

    // 调试观察点: 断点打在 std::swap 那行, 看 lesser/greater 的地址
    //             会发现它们就是 x/y 的地址(是外号, 不是副本)
}

